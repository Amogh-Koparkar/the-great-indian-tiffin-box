"""
Build step for the Tiffin Box experience.

Input : assets_4k/   (the untouched 3840x2160 originals, exact folder + file names)
Output: assets/      (1920x1080 web copies, SAME folder + file names, optimised PNGs)
        hitmasks.js  (tiny 1-bit alpha masks used for precise hover / click hit-testing,
                      pre-baked so the site also works when opened straight from disk)

Re-run after swapping any illustration:   python tools/build_assets.py
"""
import os, base64, json, subprocess, shutil
import numpy as np
from PIL import Image

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(HERE, "assets_4k")
DST = os.path.join(HERE, "assets")
W, H = 1920, 1080            # stage units used by the site (all pivots are in these units)
MW, MH = 384, 216            # hit-mask resolution (5 stage px per cell)

# layers that need pixel-accurate pointer hit testing
MASKED = {
    "kitchen scene": ["rice", "oil", "masala", "onion", "lemon juice", "cashew and nuts"],
    "school scene": ["boy 2", "main boy", "boy 3", "girl 1", "girl 2"],
}

os.makedirs(DST, exist_ok=True)
masks = {}
for root, _, files in os.walk(SRC):
    rel = os.path.relpath(root, SRC)
    out_dir = os.path.join(DST, rel) if rel != "." else DST
    os.makedirs(out_dir, exist_ok=True)
    for f in files:
        sp = os.path.join(root, f)
        dp = os.path.join(out_dir, f)
        low = f.lower()
        if low.endswith(".png"):
            im = Image.open(sp).convert("RGBA")
            # Full-stage layers are 3840x2160 (16:9); square-ish dish card photos keep their native aspect ratio
            if abs(im.size[0] / im.size[1] - (W / H)) < 0.08:
                im = im.resize((W, H), Image.LANCZOS)
            elif im.size[0] > 900:
                nh = int(round(800 * im.size[1] / im.size[0]))
                im = im.resize((800, nh), Image.LANCZOS)
            im.save(dp, optimize=True)
            key = os.path.splitext(f)[0]
            if rel in MASKED and key in MASKED[rel]:
                a = np.asarray(im.split()[3].resize((MW, MH), Image.BOX))
                bits = (a > 70).astype(np.uint8).flatten()
                masks[rel.replace(" scene", "") + "/" + key] = base64.b64encode(np.packbits(bits).tobytes()).decode()
        elif low.endswith(".mp4"):
            # 1080p h264 copy of the opening animation (4K original stays in assets_4k)
            subprocess.run(["ffmpeg", "-v", "error", "-y", "-i", sp, "-vf", "scale=1920:1080:flags=lanczos",
                            "-c:v", "libx264", "-crf", "17", "-preset", "slow", "-pix_fmt", "yuv420p",
                            "-movflags", "+faststart", "-an", dp], check=True)
        else:
            shutil.copy2(sp, dp)
        print("built", os.path.join(rel, f))

with open(os.path.join(HERE, "hitmasks.js"), "w") as fh:
    fh.write("/* AUTO-GENERATED by tools/build_assets.py - do not edit */\n")
    fh.write("window.HIT_MASKS = " + json.dumps({"w": MW, "h": MH, "data": masks}) + ";\n")
print("done")
